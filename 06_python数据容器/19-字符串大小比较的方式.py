# ASCII码表知识点
# 1. 程序里字符串包含的三类字符都有专属ASCII数字码值：
#    ① 大小写英文字母
#    ② 数字 0~9
#    ③ 特殊符号：!、\、|、@、#、空格等各类符号
# 2. 规则：每一个字符一一对应一个数字码值
# 3. 字符串大小比较底层逻辑：按照字符对应的ASCII码数字大小依次比较

# 常用ASCII关键区间（方便记忆）
# 空格：32
# 数字0-9：ASCII 48 ~ 57
# 大写字母A-Z：ASCII 65 ~ 90
# 小写字母a-z：ASCII 97 ~ 122

# Python获取字符ASCII值：ord("字符")
# 根据数字转回字符：chr(ASCII数字)
# 示例
# print(ord("A"))  # 65
# print(chr(97))   # a

