# 字符串比较规则
# 1、字符串整体比较方式：
# 从头到尾逐个字符依次对比，只要某一位字符分出大小，后续字符不再比较
# 2、单个字符大小判断依据：
# 根据ASCII码表，使用字符对应的数字码值判断大小，码值数字越大字符越大