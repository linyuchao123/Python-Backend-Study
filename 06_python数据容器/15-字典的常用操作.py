# ====================== 字典新增、更新元素 知识点注释 ======================
# 通用语法：字典[Key] = Value
# 分两种情况：key不存在则新增键值对；key已存在则覆盖更新value

# 一、新增元素：字典内没有该key，执行赋值会新增这条数据
# 语法：字典[Key] = Value
# 二、更新元素：字典已有该key，执行赋值会修改原有value
# 语法：字典[Key] = Value
# 核心规则：字典的key不能重复，重复赋值直接覆盖旧值

my_dict = {"周杰伦": 99,"林俊杰": 88,"张学友": 77}
# 新增元素
my_dict["张信哲"] = 66
print(f"字典经过新增元素后，结果：: {my_dict}")
# 更新元素
my_dict["周杰伦"] = 33
print(f"字典经过更新后，结果：: {my_dict}")

# 字典常用操作：删除、清空 注释整理
# ========== 1. pop() 根据key删除键值对 ==========
# 语法：字典.pop(Key)
# 作用：删除指定key对应的整条键值对，同时返回被删掉的value

# ========== 2. clear() 清空整个字典 ==========
# 语法：字典.clear()
# 作用：清空字典内所有键值对，字典变成空字典{}
# stu_score.clear()
# print(stu_score)   # 最终打印空字典 {}

# 删除元素pop
score = my_dict.pop("周杰伦")
print(f"字典中被移除了一个元素，结果：{my_dict},周杰伦的考试分数是: {score}")

# 清空元素clear
my_dict.clear()
print(f"字典被清空了，内容是: {my_dict}")

# 字典操作：keys() 获取字典全部键
# 语法：字典.keys()
# 作用：提取字典中所有的key，返回dict_keys类型对象

# 获取全部的key
my_dict = {"周杰伦": 99,"林俊杰": 88,"张学友": 77}
keys = my_dict.keys()
print(f"字典的全部keys是: {keys}")

# 遍历字典
# 方式1:通过获取到全部的key来完成遍历
for key in keys:
    print(f"字典的key是:{key}")
    print(f"字典的value是:{my_dict[key]}")

# 方式2:直接对字典进行for循环，每一次循环都是直接得到key
for key in my_dict:
    print(f"字典的key是:{key}")
    print(f"字典的value是:{my_dict[key]}")

# 统计字典内的元素数量，len()函数
num = len(my_dict)
print(f"字典中的元素数量有:{num}个")

