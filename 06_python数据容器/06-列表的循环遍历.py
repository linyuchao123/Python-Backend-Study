# 列表的遍历 - while循环
# 既然数据容器可以存储多个元素，那么，就会有需求从容器内依次取出元素进行操作。
# 将容器内的元素依次取出进行处理的行为，称之为：遍历、迭代。

# 如何遍历列表的元素？
# 1. 使用while循环

# 循环取元素的方式：
# 通过 列表[下标] 获取元素

# while循环控制逻辑：
# 1. 下标变量初始值为0
# 2. 循环条件：下标 < 列表总元素个数

def list_while_func():
    """
    使用while循环遍历列表的演示函数
    :return: None
    """
    my_list = ["传智教育","黑马程序员","pyhton"]
    # 循环控制变量通过下标索引来控制，默认0
    # 每一次循环将下标索引变量+1
    # 循环条件：下标索引变量 < 列表的元素数量

    # 定义一个变量用来标记列表的下标
    index = 0    # 初始值为0
    while index < len(my_list):
         # 通过index变量取出对应下标的元素
        element = my_list[index]
        print(f"列表的元素:{element}")

        # 至关重要 将循环变量（index）每一次循环都+1
        index += 1

list_while_func()

# 列表的遍历 - for循环
# Python除while循环外还有for循环，for循环更适合遍历列表等容器

# for循环语法：
# for 临时变量 in 数据容器:
#     执行代码（处理临时变量）

# 执行逻辑：
# 1. 逐个取出容器中的元素赋值给临时变量
# 2. 每次循环内部处理临时变量里的元素

def list_for_func():
    """
    使用for循环遍历列表的演示函数
    :return: None
    """

    mylist = [1,2,3,4,5]
    # for   临时变量   in   数据容易
    for element in mylist:
        print(f"列表的元素有:{element}")

list_for_func()

