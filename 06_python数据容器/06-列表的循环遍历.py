# 列表遍历总结
# 1.遍历定义：依次取出容器内所有元素并做处理
# 2.列表遍历两种方式：while循环、for循环
# 3.for循环语法
#   for 临时变量 in 数据容器:
#       处理临时变量
# 4.两种循环区别：
#            for：代码简洁，主打遍历容器
