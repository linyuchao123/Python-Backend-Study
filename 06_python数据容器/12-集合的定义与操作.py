# ====================集合引入知识点注释====================
# 已学三种数据容器：列表、元组、字符串
# 1.列表：可修改，有序，支持存放重复元素
# 2.元组、字符串：不可修改，有序，支持存放重复元素

# 原有容器的局限：全都可以存放重复元素
# 如果业务需要对数据去重，列表、元组、字符串处理很麻烦

# 集合的优势：专门适配去重场景
# 集合两大核心特征：元素自动去重、内容无序
# 因为无序，集合不支持下标索引，也不能做切片操作
# ==========================================================

# =====================集合定义语法=====================
# 1.集合字面量格式：{元素, 元素, ……, 元素}
# 2.集合变量定义格式：变量名 = {元素, 元素, ……, 元素}
# 3.定义空集合：必须用 变量名 = set()
# 注意：{} 是空字典，不能用来创建空集合

# 四种容器符号区分
# 列表：[] 方括号
# 元组：() 小括号
# 字符串："" 双引号 / '' 单引号
# 集合：{} 大括号
# =====================================================

# 定义集合：
my_set = {"传智教育","黑马程序员","itheima","传智教育","黑马程序员","itheima","传智教育","黑马程序员","itheima"}
my_set_empty = set()
print(f"my_set的内容是：{my_set},类型是：{type(my_set)}")
print(f"my_set_empty的内容是: {my_set_empty}，类型是：{type(my_set_empty)}")

# =================集合修改操作-add添加元素=================
# 重要前提：集合无序，不支持下标索引取值
# 集合支持修改，add用于向集合添加单个元素

# 语法：集合.add(元素)
# 特点：直接修改原集合；添加重复元素不会报错，集合自动去重

# 添加新元素
my_set.add("python")
my_set.add("传智教育")
print(f"my_set添加元素后,结果是：{my_set}")

# =================集合操作：remove删除指定元素=================
# 语法：集合.remove(元素)
# 功能：删除集合中指定的元素，直接修改原集合
# 重要注意：如果要删除的元素不存在，代码会直接报错

# 移除元素
my_set.remove("黑马程序员")
print(f"移除黑马程序员后，结果是:{my_set}")

# =================集合pop随机取出元素、clear清空集合=================
# 一、pop()：随机取出并删除一个元素
# 语法：集合.pop()
# 特点：1.无参数，随机拿出1个元素，可以用变量接收取出的值
#      2.原集合会删掉该元素；空集合调用pop会报错
# 列表pop可以指定下标，集合无序，pop只能随机删

# 随机取出一个元素
my_set = {"传智教育","黑马程序员","itheima"}
element = my_set.pop()
print(f"集合被取出元素是：:{element}，取出元素后:{my_set}")

# 清空集合
my_set.clear()
print(f"集合被清空了，结果是:{my_set}")

# =================集合操作：difference 求差集=================
# 语法：集合1.difference(集合2)
# 含义：找出【集合1存在、集合2不存在】的元素
# 重要：生成全新集合，原始集合1、集合2都不会被修改

# 取两个集合的差集：difference
set1 = {1,2,3}
set2 = {1,5,6}
set3 = set1.difference(set2)
print(f"取出差集后的结果是：{set3}")
print(f"取差集后，原有set1的内容：{set1}")
print(f"取差集后，原有set2的内容：{set2}")

# =========集合 difference_update 修改自身求差集=========
# 语法：集合1.difference_update(集合2)
# 作用：直接修改集合1，删掉集合1里和集合2重复的元素，只保留集合1独有的内容
# 区别于difference：difference返回新集合，原集合不变；此方法直接改动集合1，集合2始终不变

# 删除2个集合的差集
set1 = {1,2,3}
set2 = {1,5,6}
set3 = set1.difference_update(set2)
print(f"消除差集后，集合1的结果是：{set1}")
print(f"消除差集后，集合2的结果是：{set2}")

# =================集合 union 合并（并集）=================
# 语法：集合1.union(集合2)
# 功能：合并两个集合，自动去重，返回全新集合
# 特点：原集合1、集合2都不会被修改
# 简写写法：set1 | set2 等同于 union

# 2个集合合并成1个
set1 = {1,2,3}
set2 = {1,5,6}
set3 = set1.union(set2)
print(f"2集合合并后结果：{set3}")
print(f"合并后集合1:{set1}")
print(f"合并后集合2:{set2}")

# 统计集合数量
set1 = {1,2,3,4,5}  # 重复的算一个
num = len(set1)
print(f"集合内的元素数量有:{num}个")

# 集合的遍历
# 集合不支持下标索引，不能用while循环
# 可以用for循环
set1 = {1,2,3,4,5}
for element in set1:
    print(f"集合的元素有：{element}")

