# ===================== 账单文件处理需求分析 =====================
# 最终需要完成三件事：
# 1、读取bill.txt原始账单文件
# 2、把全部原始内容写入bill.txt.bak，做成完整备份文件
# 3、过滤数据，舍弃remarks备注为“测试”的行，只保留正式数据

# ---------------------- 整体实现思路 ----------------------
# 1. 使用open() + r只读模式打开bill.txt，创建文件对象用来读取全部内容
# 2. 使用open() + w写入模式打开bill.txt.bak，创建文件对象用来写入备份内容
# 3. for循环逐行读取原始文件的每一行
#    判断当前行末尾备注字段：
#    - 备注是“测试”：执行continue跳过这一行，不写入备份
#    - 备注是“正式”：正常write写入备份文件
# 4. 全部读写完成后，对读取、写入两个文件对象都调用close()关闭，释放资源

# 补充：逐行循环处理，按需过滤数据

# 打开文件得到文件对象，准备读取
fr = open('bill.txt',"r",encoding="utf-8")
# 打开文件得到文件对象，准备写入
fw = open('bill.txt.bak',"w",encoding="utf-8")
# for循环读取文件
for line in fr:
    line = line.strip()
    # 判断内容，将满足的内容写出
    if line.split(",")[4] == "测试":
        continue    # continue进入下一次循环，这一次后面的内容就跳过了
      # 将内容写出去
    fw.write(line)
    # 由于前面对内容进行了strip()的操作，所以要手动的写出换行符
    fw.write("\n")

# close2个文件对象
fr.close()
fw.close()   # 写出文件调用close会自动调用flush刷新功能