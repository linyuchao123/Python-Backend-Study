# ====================== 元字符匹配 ======================
# 之前练习的是普通字符串匹配，正则核心优势在于元字符匹配规则
# -------------------- 单字符匹配元字符对照表 --------------------
# .    ：匹配任意1个字符（换行符\n除外）；使用 \. 可以匹配圆点本身
# []   ：匹配方括号内部列举出的字符
# \d   ：匹配数字，等价0-9
# \D   ：匹配非数字内容
# \s   ：匹配空白字符，包含空格、tab制表符
# \S   ：匹配非空白字符
# \w   ：匹配单词字符：小写字母a-z、大写字母A-Z、数字0-9、下划线_
# \W   ：匹配非单词字符

# -------------------- 代码示例演示 --------------------
import re
s = "itheima1 @@python2 !!666 ##itcast3"

# 1. 提取全部数字
# r前缀代表原始字符串：让字符串里的转义符号失去转义效果，按普通字符解析
res_num = re.findall(r'\d', s)

# 2. 提取全部英文字母
res_letter = re.findall(r'[a-zA-Z]', s)

# []用法拓展：括号内可组合区间 [a-zA-Z0-9]，也可罗列指定字符如[aceDFG135]
# 比如 [a-zA-Z0-9] 就可以同时匹配字母和数字